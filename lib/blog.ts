/** Все статьи, свежие сверху */
export function getPosts(): BlogPost[] {
  return [...posts].sort((a, b) => b.date.localeCompare(a.date));
}

export function getPost(slug: string): BlogPost | undefined {
  return posts.find((p) => p.slug === slug);
}

const dateFormat = new Intl.DateTimeFormat("ru-RU", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });

/** «28 августа 2026» */
export function formatPostDate(date: string): string {
  return dateFormat.format(new Date(`${date}T00:00:00Z`)).replace(/\s*г\.$/, "");
}

/** Примерное время чтения в минутах (~180 слов в минуту) */
export function readingMinutes(post: BlogPost): number {
  return Math.max(1, Math.round(post.content.split(/\s+/).filter(Boolean).length / 180));
}
